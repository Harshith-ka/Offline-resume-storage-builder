function createDoc(overrides: Partial<ResumeDocument> & Pick<ResumeDocument, "id" | "name">): ResumeDocument {
  const now = new Date().toISOString();
  return {
    id: overrides.id,
    name: overrides.name,
    createdAt: now,
    updatedAt: now,
    version: 1,
    pages: [
      {
        id: "page-1",
        width: 794,
        height: 1123,
        margin: 48,
        blocks: [],
      },
    ],
    ...overrides,
  };
}

